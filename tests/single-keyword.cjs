const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('app.js', 'utf8');
const controls = { bulkMarketplace: {value:'US'}, bulkBiddingStrategy:{value:'Fixed bid'} };
const ctx = vm.createContext({ console, Intl, localStorage:{getItem:()=>null}, window:{}, document:{getElementById:id=>controls[id]} });
vm.runInContext(source.slice(0, source.lastIndexOf('\nbindEvents();')), ctx);
const run = code => vm.runInContext(code, ctx);
run(`var config = {products:'SKU:MY-BANDANA-BAG', prefix:'SP-bag', marketplace:'US', budget:12, bid:0.5, match:'exact'};
var generated = createSingleKeywordCampaigns('bandana bag\\nBandana Bag\\n  bandana   tote bag  \\n\\n',config,[]);`);
assert.equal(run('generated.length'),2);
assert.equal(run('new Set(generated.map(c=>c.id)).size'),2);
assert.equal(run('generated[1].keywords'),'bandana tote bag');
assert.equal(run('generated[0].biddingStrategy'),'Fixed bid');
assert.equal(run('generated[0].name'),'SP-bag-exact-bandana bag');
assert.equal(run('generated[0].placementTop'),0);
run(`var multiMatch = createSingleKeywordCampaigns('bandana bag\\nbandana purse', {...config, matches:['exact','phrase','broad']}, []);`);
assert.equal(run('multiMatch.length'),6);
assert.deepEqual(JSON.parse(run('JSON.stringify(multiMatch.map(c=>c.matchType))')),['exact','phrase','broad','exact','phrase','broad']);
run(`var individualBids = createSingleKeywordCampaigns('bandana bag\\nbandana purse', {...config, bidMode:'individual', individualBids:'0.35\\n0.72', matches:['exact','phrase']}, []);`);
assert.deepEqual(JSON.parse(run('JSON.stringify(individualBids.map(c=>c.defaultBid))')),[0.35,0.35,0.72,0.72]);
run(`var placed = createSingleKeywordCampaigns('bandana bag', {...config, placementTop:50, placementRest:25, placementProduct:100}, []);`);
assert.deepEqual(JSON.parse(run('JSON.stringify([placed[0].placementTop, placed[0].placementRest, placed[0].placementProduct])')),[50,25,100]);
run(`var placementRows = buildRowsForCampaign(placed[0],0,{marketplace:'US',startDate:'20261110',portfolioId:''}).filter(r=>r.Entity === 'Bidding adjustment');`);
assert.deepEqual(JSON.parse(run('JSON.stringify(placementRows.map(r=>r.Percentage))')),[50,25,100]);
run(`var keywordGroups = createSingleKeywordCampaigns('', {...config, matches:[], keywordGroups:['product','category'], keywordGroupBid:0.61}, []);`);
assert.equal(run('keywordGroups.length'),2);
assert.deepEqual(JSON.parse(run('JSON.stringify(keywordGroups.map(c=>c.keywordGroupExpression))')),['keyword-group="product"','keyword-group="category"']);
assert.equal(run('keywordGroups.every(c=>c.type === "keywordGroup" && c.defaultBid === 0.61)'),true);
run(`var keywordGroupRows = keywordGroups.flatMap((c,i)=>buildRowsForCampaign(c,i,{marketplace:'US',startDate:'20261110',portfolioId:''}));`);
assert.equal(run('keywordGroupRows.filter(r=>r.Entity === "Product targeting").length'),2);
assert.equal(run('keywordGroupRows.filter(r=>r.Entity === "Keyword").length'),0);
assert.deepEqual(JSON.parse(run('JSON.stringify(keywordGroupRows.filter(r=>r.Entity === "Product targeting").map(r=>r["Product Targeting Expression"]))')),['keyword-group="product"','keyword-group="category"']);
run(`var mixedTargeting = createSingleKeywordCampaigns('bandana bag', {...config, matches:['exact','phrase'], keywordGroups:['category'], keywordGroupBid:0.6}, []);`);
assert.equal(run('mixedTargeting.length'),3);
assert.equal(run('createSingleKeywordCampaigns("bandana bag", {...config, prefix:""}, [])[0].name'),'MY-BANDANA-BAG-exact-bandana bag');
assert.equal(run('createSingleKeywordCampaigns("bandana bag", {...config, prefix:"", products:"B012345678, MY-SKU"}, [])[0].name'),'MY-SKU-exact-bandana bag');
assert.equal(run('createSingleKeywordCampaigns("bandana bag", {...config, prefix:"", products:"B012345678"}, [])[0].name'),'B012345678-exact-bandana bag');
for (const match of ['exact','phrase','broad']) {
  ctx.match = match;
  run(`generated = createSingleKeywordCampaigns('bandana bag\\nbandana purse', {...config, match}, []);
    var rows = generated.flatMap((c,i)=>buildRowsForCampaign(c,i,{marketplace:'US',startDate:'20261110',portfolioId:''}));`);
  assert.equal(run('rows.filter(r=>r.Entity === "Campaign").length'),2);
  assert.equal(run('rows.filter(r=>r.Entity === "Keyword").length'),2);
  assert.equal(run('rows.filter(r=>r.Entity === "Ad group").length'),2);
  assert.equal(run('rows.filter(r=>r.Entity === "Keyword").every(r=>r["Match Type"] === match && r.Bid === 0.5)'),true);
  assert.equal(run('new Set(rows.filter(r=>r.Entity === "Keyword").map(r=>r["Campaign Id"])).size'),2);
}
run(`var collision = createSingleKeywordCampaigns('bandana bag', {...config,match:'broad'},generated);`);
assert.notEqual(run('collision[0].name'),run('generated[0].name'));
assert.equal(run('JSON.parse(JSON.stringify(generated))[0].keywords'),'bandana bag');
assert.throws(()=>run(`createSingleKeywordCampaigns('',config,[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag, 0.5',config,[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,products:''},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,bid:-1},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,placementTop:901},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,placementRest:1.5},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,matches:[]},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('',{...config,matches:[],keywordGroups:['unknown'],keywordGroupBid:0.5},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('',{...config,matches:[],keywordGroups:['product'],keywordGroupBid:0.01},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,bidMode:'individual'},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag',{...config,bidMode:'individual',individualBids:'0.01'},[])`));
assert.throws(()=>run(`createSingleKeywordCampaigns('bag\\npurse',{...config,bidMode:'individual',individualBids:'0.5'},[])`));
console.log('Single-keyword generation, keyword groups, deduplication, name collisions, 3 match types and real export: passed');
